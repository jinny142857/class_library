// 공공데이터포털 한국천문연구원 특일 정보 API (선택)
export async function fetchHolidaysFromApi(year, apiKey) {
  const out = [];
  for (let m = 1; m <= 12; m++) {
    const url = `https://apis.data.go.kr/B090041/openapi/service/SpcdeInfoService/getRestDeInfo?serviceKey=${encodeURIComponent(apiKey)}&solYear=${year}&solMonth=${String(m).padStart(2, '0')}&_type=json&numOfRows=50`;
    const res = await fetch(url, { signal: AbortSignal.timeout(8000) });
    if (!res.ok) throw new Error(`공휴일 API 오류 (${res.status})`);
    const json = await res.json();
    let items = json?.response?.body?.items?.item;
    if (!items) continue;
    if (!Array.isArray(items)) items = [items];
    for (const it of items) {
      if (it.isHoliday !== 'Y') continue;
      const s = String(it.locdate);
      out.push([`${s.slice(0, 4)}-${s.slice(4, 6)}-${s.slice(6, 8)}`, it.dateName]);
    }
  }
  return out;
}
